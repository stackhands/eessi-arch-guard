#!/usr/bin/env python3
"""Write zig/pylower_table.zig: what str.lower() does past ASCII.

The Zig guard lower-cases a cpuinfo field name the way the Python guard does
with ``str.lower()``. Zig has no Unicode case tables of its own, so the
tables are read off the Python interpreter that runs this script:

* ``lower_runs``: the code points past ASCII whose lower case is one other
  code point, as runs of equal distance: a first and a last code point, a
  stride of 1 or 2 between the members, and the signed distance to the lower
  case. U+212A, the Kelvin sign, is in a run of its own and gives ``k``.
* ``lower_special``: the code points whose lower case is two code points.
  U+0130 gives ``i`` and U+0307.
* ``cased`` and ``case_ignorable``: the ranges of code points that decide
  whether a capital sigma is word-final, which ``str.lower()`` writes as
  U+03C2 and otherwise as U+03C3. ``cased`` holds the code points that are
  cased and not case-ignorable, ``case_ignorable`` those that are skipped.
  Python reads them from the Unicode database; here they are found by the
  effect each code point has on a sigma next to it, so the script needs
  nothing but the interpreter.

The tables are those of one Unicode version, which the file names. Run
``python3 tools/gen_pylower.py`` and then ``zig fmt zig`` to refresh them
when a newer Python carries a newer Unicode. ``tests/test_pylower_table.py``
checks the file against the interpreter over every code point.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

TARGET = Path(__file__).resolve().parent.parent / "zig" / "pylower_table.zig"
SIGMA = "\u03a3"
LAST = 0x10FFFF

LowerMap = List[Tuple[int, Tuple[int, ...]]]
Run = Tuple[int, int, int, int]
Ranges = List[Tuple[int, int]]


def code_points() -> List[int]:
    """Every code point a UTF-8 decoder can produce: all but the surrogates."""
    return [cp for cp in range(LAST + 1) if not 0xD800 <= cp <= 0xDFFF]


def lower_map() -> LowerMap:
    found: LowerMap = []
    for cp in code_points():
        if cp < 0x80:
            continue
        lowered = chr(cp).lower()
        if lowered != chr(cp):
            found.append((cp, tuple(ord(ch) for ch in lowered)))
    return found


def lower_runs(found: LowerMap) -> List[Run]:
    """The single-code-point mappings as (first, last, stride, delta) runs."""
    runs: List[Run] = []
    for cp, lowered in found:
        if len(lowered) != 1:
            continue
        delta = lowered[0] - cp
        if runs:
            first, last, stride, run_delta = runs[-1]
            gap = cp - last
            if run_delta == delta and gap in (1, 2) and (stride in (0, gap)):
                runs[-1] = (first, cp, gap, delta)
                continue
        runs.append((cp, cp, 0, delta))
    return [(first, last, stride or 1, delta) for first, last, stride, delta in runs]


def lower_special(found: LowerMap) -> LowerMap:
    return [(cp, lowered) for cp, lowered in found if len(lowered) != 1]


def sigma_classes() -> Tuple[Ranges, Ranges]:
    """Ranges of the code points that count as cased, and that are skipped."""
    cased: List[int] = []
    ignorable: List[int] = []
    for cp in code_points():
        ch = chr(cp)
        before = (ch + SIGMA).lower().endswith("\u03c2")
        between = ("a" + ch + SIGMA).lower().endswith("\u03c2")
        if before:
            cased.append(cp)
        elif between:
            ignorable.append(cp)
    return to_ranges(cased), to_ranges(ignorable)


def to_ranges(values: Sequence[int]) -> Ranges:
    ranges: Ranges = []
    for value in values:
        if ranges and ranges[-1][1] + 1 == value:
            ranges[-1] = (ranges[-1][0], value)
        else:
            ranges.append((value, value))
    return ranges


def tables() -> Dict[str, object]:
    cased, ignorable = sigma_classes()
    found = lower_map()
    return {
        "unicode_version": unicodedata.unidata_version,
        "lower_runs": lower_runs(found),
        "lower_special": lower_special(found),
        "cased": cased,
        "case_ignorable": ignorable,
    }


def render(data: Dict[str, object]) -> str:
    lines = [
        "//! Generated by tools/gen_pylower.py; do not edit by hand.",
        "//!",
        "//! What str.lower() does past ASCII, and the character classes that decide",
        "//! whether a capital sigma is word-final. See zig/pylower.zig.",
        "",
        'pub const unicode_version = "%s";' % data["unicode_version"],
        "",
        "/// Code points whose lower case is one other code point: the members are",
        "/// `first`, `first + stride`, and so on up to `last`, and each lowers to its",
        "/// own value plus `delta`.",
        "pub const Run = struct { first: u21, last: u21, stride: u2, delta: i32 };",
        "",
        "/// A code point whose lower case is two code points.",
        "pub const Special = struct { cp: u21, to: [2]u21 };",
        "",
        "pub const lower_runs = [_]Run{",
    ]
    for first, last, stride, delta in data["lower_runs"]:  # type: ignore[attr-defined]
        lines.append(
            "    .{ .first = 0x%04X, .last = 0x%04X, .stride = %d, .delta = %d }," % (first, last, stride, delta)
        )
    lines += ["};", "", "pub const lower_special = [_]Special{"]
    for cp, lowered in data["lower_special"]:  # type: ignore[attr-defined]
        if len(lowered) != 2:
            raise SystemExit("U+%04X lower-cases to %d code points" % (cp, len(lowered)))
        lines.append("    .{ .cp = 0x%04X, .to = .{ 0x%04X, 0x%04X } }," % (cp, lowered[0], lowered[1]))
    lines += ["};", ""]
    for name, doc in (
        ("cased", "Code points that are cased and not case-ignorable, as inclusive ranges."),
        ("case_ignorable", "Code points that are case-ignorable, as inclusive ranges."),
    ):
        lines.append("/// " + doc)
        lines.append("pub const %s = [_][2]u21{" % name)
        for first, last in data[name]:  # type: ignore[attr-defined]
            lines.append("    .{ 0x%04X, 0x%04X }," % (first, last))
        lines += ["};", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> int:
    TARGET.write_text(render(tables()), encoding="utf-8")
    print("wrote %s for Unicode %s" % (TARGET, unicodedata.unidata_version))
    return 0


if __name__ == "__main__":
    sys.exit(main())
